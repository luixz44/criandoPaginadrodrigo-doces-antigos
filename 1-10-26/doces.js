const areaDosDoces = document.getElementById("lista-de-doces");
const formularioDeDoce = document.getElementById("formulario-de-doce");
const campoNomeDoDoce = document.getElementById("campo-nome-do-doce");
const campoLinkDaFoto = document.getElementById("campo-link-da-foto");
const campoLinkDoVideo = document.getElementById("campo-link-do-video"); // Adicionado
const campoDescricaoDoDoce = document.getElementById("campo-descricao-do-doce");

const nomeDoLugarOndeGuarda = "docesAdicionadosPeloFormulario";
let docesAdicionados = [];

function carregarDocesAdicionados() {
  try {
    const textoGuardado = localStorage.getItem(nomeDoLugarOndeGuarda);
    if (textoGuardado) {
      docesAdicionados = JSON.parse(textoGuardado);
    }
  } catch (erro) {
    docesAdicionados = [];
  }
}

function guardarDocesAdicionados() {
  try {
    localStorage.setItem(nomeDoLugarOndeGuarda, JSON.stringify(docesAdicionados));
  } catch (erro) {
  
  }
}


function criarCartaoDoDoce(doce) {
  const cartao = document.createElement("article");
  cartao.className = "cartao-do-doce";

  const areaMidia = document.createElement("div");
  areaMidia.className = "midia-do-doce";

  const foto = document.createElement("img");
  foto.className = "foto-do-doce";
  foto.src = doce.linkDaFoto;
  foto.alt = doce.nome;
  areaMidia.appendChild(foto);

  if (doce.linkDoVideo) {
    const video = document.createElement("video");
    video.className = "video-do-doce";
    video.src = doce.linkDoVideo;
    video.muted = true;
    video.loop = true;
    video.playsInline = true;
    areaMidia.appendChild(video);

    cartao.addEventListener("mouseenter", function () {
      video.play().catch(function () {
       
      });
    });

    cartao.addEventListener("mouseleave", function () {
      video.pause();
    });
  }

  cartao.appendChild(areaMidia);

  if (doce.lancamento || doce.saiuDeLinha) {
    const etiqueta = document.createElement("p");
    etiqueta.className = "etiqueta-do-doce";
    
    let textoEtiqueta = "";
    if (doce.lancamento) textoEtiqueta += `Lançamento: ${doce.lancamento}`;
    if (doce.lancamento && doce.saiuDeLinha) textoEtiqueta += " · ";
    if (doce.saiuDeLinha) textoEtiqueta += `Saiu de linha: ${doce.saiuDeLinha}`;
    
    etiqueta.textContent = textoEtiqueta;
    cartao.appendChild(etiqueta);
  }

  const nome = document.createElement("h2");
  nome.className = "nome-do-doce";
  nome.textContent = doce.nome;

  const descricao = document.createElement("p");
  descricao.className = "descricao-do-doce";
  descricao.textContent = doce.descricao;

  cartao.appendChild(nome);
  cartao.appendChild(descricao);

  return cartao;
}

function mostrarTodosOsDoces() {
  areaDosDoces.innerHTML = "";
  const todosOsDoces = listaDeDoces.concat(docesAdicionados);
  todosOsDoces.forEach(function (doce) {
    areaDosDoces.appendChild(criarCartaoDoDoce(doce));
  });
}


formularioDeDoce.addEventListener("submit", function (evento) {
  evento.preventDefault();

  const novoDoce = {
    nome: campoNomeDoDoce.value.trim(),
    linkDaFoto: campoLinkDaFoto.value.trim(),
    linkDoVideo: campoLinkDoVideo ? campoLinkDoVideo.value.trim() : "", // Adicionado
    descricao: campoDescricaoDoDoce.value.trim()
  };

  docesAdicionados.push(novoDoce);
  guardarDocesAdicionados();
  mostrarTodosOsDoces();

  formularioDeDoce.reset();
});

carregarDocesAdicionados();
mostrarTodosOsDoces();